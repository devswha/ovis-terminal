//! What ships inside the binary for an agent that has nothing else: the manual, and the
//! runtime contract reference rendered from this build's own types.

mod contract;
mod tables;

use ovis_terminal_protocol::schema::{PROTOCOL_GENERATION, SchemaError, openrpc_document};
use serde_json::Value;

/// The agent manual of this build; `docs/skill/ovis-terminal.md` is a byte-equal copy.
pub(crate) const MANUAL: &str = include_str!("skill/manual.md");

/// Renders the reference for `cli`, the command-line contract of this binary.
///
/// # Errors
///
/// Returns [`SchemaError`] when the OpenRPC document cannot be built.
pub(crate) fn contract(cli: &Value) -> Result<String, SchemaError> {
    let document = openrpc_document()?;
    let mut out = format!(
        "# ovis-terminal runtime contract\n\n\
         Reference for `{} {}`, protocol generation {}. Generated by \
         `ovis-terminal schema contract` from the types of that build; do not edit it by \
         hand.\n\n",
        crate::BINARY_NAME,
        crate::VERSION,
        PROTOCOL_GENERATION.get()
    );
    out.push_str(contract::BEHAVIOUR);
    out.push_str(&contract::methods(&document));
    out.push_str(&contract::events(&document));
    out.push_str(&contract::error_kinds(&document));
    out.push_str(&contract::limits(&document));
    out.push_str(&tables::roles());
    out.push_str(&contract::command_line(cli));
    Ok(out)
}

