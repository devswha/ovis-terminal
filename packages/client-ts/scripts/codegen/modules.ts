// Assembles the generated module tree from one OpenRPC document.

import { createHash } from "node:crypto";

import { DECIMAL_PATTERN, GenerateError, Renderer, type Schema, literals, refName, typeName } from "./render";

interface Method {
  readonly name: string;
  readonly summary?: string;
  readonly result: { readonly schema: Schema };
  readonly "x-params": Schema;
  readonly "x-effect": string;
  readonly "x-targeting": string;
}

interface Named {
  readonly name: string;
  readonly schema: Schema;
  readonly summary?: string;
}

export interface Document {
  readonly info: { readonly version: string; readonly "x-generation": string };
  readonly methods: readonly Method[];
  readonly components: { readonly schemas: Readonly<Record<string, Schema>> };
  readonly "x-events": readonly Named[];
  readonly "x-notifications": readonly Named[];
  readonly "x-error-kinds": readonly { readonly kind: string; readonly code: number; readonly description: string }[];
  readonly "x-stream": unknown;
  readonly "x-limits": { readonly defaults: Readonly<Record<string, string>> };
  readonly "x-compatibility": unknown;
}

const BRANDS = ["Decimal", "Id", "Open"] as const;

function header(digest: string): string {
  return `// Generated by scripts/generate.ts from schema/ovis-terminal.openrpc.json (sha256 ${digest}); do not edit.\n`;
}

function brandImport(body: string, from: string): string {
  const used = BRANDS.filter((brand) => new RegExp(`\\b${brand}<`).test(body));
  return used.length === 0 ? "" : `import type { ${used.join(", ")} } from "${from}";\n`;
}

/** Records that `component` declares `name`; generated name -> the component that declared it. */
function claim(names: Map<string, string>, name: string, component: string): void {
  const earlier = names.get(name);
  if (earlier !== undefined) {
    throw new GenerateError("name_collision", `components ${earlier} and ${component} both generate the declaration ${name}`, {
      target: name,
      sources: [earlier, component],
    });
  }
  names.set(name, component);
}

function components(document: Document): string {
  const render = new Renderer("");
  const names = new Map<string, string>();
  const lines = Object.keys(document.components.schemas)
    .sort()
    .map((component) => {
      const schema = document.components.schemas[component] as Schema;
      const name = typeName(component);
      claim(names, name, component);
      const values = literals(schema);
      if (values !== undefined) {
        claim(names, `${name}Values`, component);
        return `export const ${name}Values = ${JSON.stringify(values)} as const;\nexport type ${name} = (typeof ${name}Values)[number];`;
      }
      if (schema.type === "string") {
        const brand = schema.pattern === DECIMAL_PATTERN ? "Decimal" : "Id";
        return `export type ${name} = ${brand}<${JSON.stringify(name)}>;`;
      }
      return `export type ${name} = ${render.render(schema)};`;
    });
  const body = `${lines.join("\n")}\n`;
  return `${brandImport(body, "../brand")}\n${body}`;
}

function pascal(namespace: string): string {
  return namespace.replace(/(^|_)([a-z])/g, (_, __, letter: string) => letter.toUpperCase());
}

function namespaces(document: Document): Map<string, Method[]> {
  const grouped = new Map<string, Method[]>();
  for (const method of [...document.methods].sort((a, b) => a.name.localeCompare(b.name))) {
    const namespace = method.name.split(".")[0] ?? method.name;
    grouped.set(namespace, [...(grouped.get(namespace) ?? []), method]);
  }
  return grouped;
}

function methodModule(namespace: string, methods: readonly Method[]): string {
  const render = new Renderer("C.");
  const entries = methods.map((method) => {
    const params = `C.${refName(method["x-params"].$ref ?? "")}`;
    const doc = method.summary === undefined ? "" : `  /** ${method.summary} */\n`;
    return `${doc}  readonly ${JSON.stringify(method.name)}: { readonly params: ${params}; readonly result: ${render.render(method.result.schema)} };`;
  });
  const catalog = methods.map(
    (method) => `  ${JSON.stringify(method.name)}: { effect: ${JSON.stringify(method["x-effect"])}, targeting: ${JSON.stringify(method["x-targeting"])} },`,
  );
  const body = `export interface ${pascal(namespace)}Methods {\n${entries.join("\n")}\n}\n\nexport const ${namespace}Methods = {\n${catalog.join("\n")}\n} as const;\n`;
  return `${brandImport(body, "../../brand")}import type * as C from "../components";\n\n${body}`;
}

function methodIndex(groups: Map<string, Method[]>): string {
  const spaces = [...groups.keys()];
  const imports = spaces.map((space) => `import { type ${pascal(space)}Methods, ${space}Methods } from "./${space}";`);
  return `${imports.join("\n")}\n\nexport type Methods = ${spaces.map((space) => `${pascal(space)}Methods`).join(" &\n  ")};\n\nexport const methods = {\n${spaces.map((space) => `  ...${space}Methods,`).join("\n")}\n} as const;\n\nexport type RpcMethod = keyof Methods;\nexport type ParamsOf<M extends RpcMethod> = Methods[M]["params"];\nexport type ResultOf<M extends RpcMethod> = Methods[M]["result"];\n`;
}

function namedMap(title: string, entries: readonly Named[]): string {
  const render = new Renderer("C.");
  const fields = entries.map((entry) => `  readonly ${JSON.stringify(entry.name)}: ${render.render(entry.schema)};`);
  const names = JSON.stringify(entries.map((entry) => entry.name));
  const lower = title.charAt(0).toLowerCase() + title.slice(1);
  const body = `export interface ${title} {\n${fields.join("\n")}\n}\n\nexport const ${lower}Names = ${names} as const;\n`;
  return `${brandImport(body, "../brand")}import type * as C from "./components";\n\n${body}`;
}

function errors(document: Document): string {
  const rows = document["x-error-kinds"].map(
    (row) => `  ${row.kind}: { code: ${row.code}, hint: ${JSON.stringify(row.description)} },`,
  );
  return `export const errorKinds = {\n${rows.join("\n")}\n} as const;\n\nexport type KnownErrorKind = keyof typeof errorKinds;\n`;
}

function stream(document: Document): string {
  const constant = (name: string, value: unknown) => `export const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`;
  return [
    constant("protocolGeneration", document.info["x-generation"]),
    constant("schemaVersion", document.info.version),
    constant("streamContract", document["x-stream"]),
    constant("limitDefaults", document["x-limits"].defaults),
    constant("compatibility", document["x-compatibility"]),
  ].join("\n");
}

/** Every generated file, keyed by path below `src/generated/`. */
export function generate(source: string): Map<string, string> {
  const document = JSON.parse(source) as Document;
  const digest = createHash("sha256").update(source).digest("hex");
  const files = new Map<string, string>();
  const put = (path: string, body: string) => files.set(path, `${header(digest)}${body}`);
  put("components.ts", components(document));
  const groups = namespaces(document);
  for (const [namespace, methods] of groups) {
    put(`methods/${namespace}.ts`, methodModule(namespace, methods));
  }
  put("methods/index.ts", methodIndex(groups));
  put("events.ts", namedMap("Events", document["x-events"]));
  put("notifications.ts", namedMap("Notifications", document["x-notifications"]));
  put("errors.ts", errors(document));
  put("stream.ts", stream(document));
  files.set("openrpc.json", source);
  return files;
}
