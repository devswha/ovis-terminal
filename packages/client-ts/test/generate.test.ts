import { expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";

import { type Document, generate } from "../scripts/codegen/modules";
import { DECIMAL_PATTERN, GenerateError, Renderer, type Schema, typeName } from "../scripts/codegen/render";
import { methods } from "../src/generated/methods";

const SCHEMA = join(import.meta.dir, "..", "..", "..", "schema", "ovis-terminal.openrpc.json");
const source = readFileSync(SCHEMA, "utf8");
const document = JSON.parse(source) as Document;

const failure = (run: () => unknown) => {
  try {
    run();
  } catch (error) {
    return (error as GenerateError).kind;
  }
  return "generated";
};

test("every published method lands in exactly one namespace module and in the runtime catalog", () => {
  const files = generate(source);
  const names = document.methods.map((method) => method.name).sort();
  const declaredIn = names.map((name) => [...files].filter(([path, body]) => path.startsWith("methods/") && path !== "methods/index.ts" && body.includes(`readonly ${JSON.stringify(name)}:`)).map(([path]) => path));
  expect(declaredIn.every((paths, index) => paths.length === 1 && paths[0] === `methods/${names[index]?.split(".")[0]}.ts`)).toBe(true);
  expect(Object.keys(methods).sort()).toEqual(names);
  expect(files.get("openrpc.json")).toBe(source);
});

test("generation is deterministic and the committed output is that generation", () => {
  const first = generate(source);
  expect([...generate(source)]).toEqual([...first]);
  for (const [path, body] of first) {
    expect([path, readFileSync(join(import.meta.dir, "..", "src", "generated", path), "utf8") === body]).toEqual([path, true]);
  }
});

test("open-enum sites, decimals and identities render as distinct nominal types", () => {
  const body = generate(source).get("components.ts") ?? "";
  expect(body).toContain('export type ByteOffset = Decimal<"ByteOffset">;');
  expect(body).toContain('export type StreamId = Id<"StreamId">;');
  expect(body).toMatch(/"kind": Open<ControlKind>/);
  expect(new Renderer("").render({ $ref: "#/components/schemas/StreamMode" })).toBe("StreamMode");
});

test("generated modules do not depend on the insertion order of components or methods", () => {
  const reordered: Document = {
    ...document,
    methods: [...document.methods].reverse(),
    components: { schemas: Object.fromEntries(Object.entries(document.components.schemas).reverse()) },
  };
  const reorderedSource = JSON.stringify(reordered);
  expect(Object.keys(JSON.parse(reorderedSource).components.schemas)).not.toEqual(Object.keys(document.components.schemas));
  // Only the source digest in the header and the verbatim openrpc.json copy may follow the input bytes.
  const modules = (text: string) =>
    [...generate(text)].filter(([path]) => path !== "openrpc.json").map(([path, body]) => [path, body.replace(/^\/\/ Generated by .*\n/, "")]);
  const original = modules(source);
  expect(original.length).toBeGreaterThan(3);
  expect(modules(reorderedSource)).toEqual(original);
});

// The smallest document the generator accepts, carrying the given components and one method.
const minimal = (schemas: Record<string, Schema>, params: string): string =>
  JSON.stringify({
    info: { version: "0.0.0", "x-generation": "1" },
    methods: [{ name: "probe.get", result: { schema: { $ref: `#/components/schemas/${params}` } }, "x-params": { $ref: `#/components/schemas/${params}` }, "x-effect": "read", "x-targeting": "none" }],
    components: { schemas },
    "x-events": [],
    "x-notifications": [],
    "x-error-kinds": [],
    "x-stream": {},
    "x-limits": { defaults: {} },
    "x-compatibility": {},
  });

test("schemars component names map to deterministic PascalCase identifiers at declarations and references", () => {
  const files = generate(
    minimal(
      {
        ProcessSample: { type: "object", properties: { pid: { type: "string", pattern: DECIMAL_PATTERN } }, required: ["pid"] },
        Observed_Array_of_ProcessSample: { type: "array", items: { $ref: "#/components/schemas/ProcessSample" } },
        sample_2_window: { type: "string" },
        Probe_Params: {
          type: "object",
          properties: { tree: { $ref: "#/components/schemas/Observed_Array_of_ProcessSample" }, window: { $ref: "#/components/schemas/sample_2_window" } },
          required: ["tree", "window"],
        },
      },
      "Probe_Params",
    ),
  );
  const components = files.get("components.ts") ?? "";
  expect(components).toContain("export type ObservedArrayOfProcessSample = readonly (ProcessSample)[];");
  expect(components).toContain('export type Sample2Window = Id<"Sample2Window">;');
  expect(components).toContain('export type ProbeParams = { readonly "tree": ObservedArrayOfProcessSample; readonly "window": Sample2Window };');
  expect(files.get("methods/probe.ts")).toContain('readonly "probe.get": { readonly params: C.ProbeParams; readonly result: C.ProbeParams };');
  expect(typeName("Observed_Array_of_ProcessSample")).toBe("ObservedArrayOfProcessSample");
  expect(typeName("StreamMode")).toBe("StreamMode");
  const declared = [...components.matchAll(/^export (?:type|const) (\w+)/gm)].map((match) => match[1]);
  expect(declared.every((name) => /^[A-Z][A-Za-z0-9]*$/.test(name ?? ""))).toBe(true);
});

test("a name collision after mapping fails generation with the typed name_collision error naming both components", () => {
  const thrown = (() => {
    try {
      generate(minimal({ Foo_Bar: { type: "string" }, FooBar: { type: "boolean" } }, "FooBar"));
    } catch (error) {
      return error;
    }
    return undefined;
  })();
  expect(thrown).toBeInstanceOf(GenerateError);
  const error = thrown as GenerateError;
  expect([error.kind, error.target, [...error.sources].sort()]).toEqual(["name_collision", "FooBar", ["FooBar", "Foo_Bar"]]);
});

test("a component name with no valid TypeScript identifier mapping is refused, never emitted", () => {
  expect(failure(() => typeName("2_fast"))).toBe("unsupported_schema");
  expect(failure(() => typeName("__"))).toBe("unsupported_schema");
  expect(failure(() => generate(minimal({ "9Lives": { type: "string" } }, "9Lives")))).toBe("unsupported_schema");
});

test("an unsupported schema or a colliding name fails generation with a typed kind", () => {
  expect(failure(() => new Renderer("").render({ type: "tuple" }))).toBe("unsupported_schema");
  expect(failure(() => new Renderer("").render({ $ref: "#/definitions/Elsewhere" }))).toBe("unsupported_schema");
  const colliding = { ...document, components: { schemas: { ...document.components.schemas, ControlKindValues: { type: "string" } } } };
  expect(failure(() => generate(JSON.stringify(colliding)))).toBe("name_collision");
});
